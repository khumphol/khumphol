/** แปลข้อความ + แทนค่า placeholder เช่น docs_t('doc.trash_hint_days', [':d' => 30]) */
function docs_t($key, array $replace = []){
    $L = docs_lang();
    $v = $L[$key] ?? $key;
    foreach($replace as $k => $r) $v = str_replace($k, (string)$r, $v);
    return $v;
}

